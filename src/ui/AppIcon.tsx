export interface AppIconProps {
  name: AppIconName | null | undefined;
  size?: number;
  color: string;
  strokeWidth?: number;
}

export function AppIcon({
  name,
  size = 20,
  color,
  strokeWidth = 1.75,
}: AppIconProps) {
  const IconComp = (name ? ICON_MAP[name] : undefined) ?? Shapes;
  return <IconComp size={size} color={color} strokeWidth={strokeWidth} />;
}
